CREATE OR ALTER PROCEDURE dbo.nt_DirtyRead_T2
    @MaTK varchar(10) = 'A001'
AS
BEGIN
    SET NOCOUNT ON;
    SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;
    BEGIN TRANSACTION;
    SELECT * FROM dbo.TaiKhoan WHERE MaTK = @MaTK;
    COMMIT TRANSACTION;
END;
GO

EXEC dbo.nt_DirtyRead_T2;
