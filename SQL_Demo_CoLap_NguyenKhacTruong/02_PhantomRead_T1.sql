GO

CREATE OR ALTER PROCEDURE dbo.nt_PhantomRead_T1
AS
BEGIN
    SET NOCOUNT ON;
    SET TRANSACTION ISOLATION LEVEL READ COMMITTED;
    BEGIN TRANSACTION;
    UPDATE dbo.TaiKhoan
    SET TenTK = N'NguyenKhacTruong'
    WHERE SoTien > 150000;
    WAITFOR DELAY '00:00:10';
    SELECT * FROM dbo.TaiKhoan WHERE SoTien > 150000;
    COMMIT TRANSACTION;
END;
GO

EXEC dbo.nt_PhantomRead_T1;
